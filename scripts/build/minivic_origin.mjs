#!/usr/bin/env node
/**
 * Writes `app/data/generated/minivic-origin.ts` — the Cloud Run origin MiniVic
 * sends to directly, resolved once at build time.
 *
 * WHY A BUILD SCRIPT AND NOT A LITERAL IN THE CLIENT
 * --------------------------------------------------
 * The run.app hostname belongs to a deployment, not to the code: recreate the
 * function and it changes. A component holding it would be a component that has
 * to be edited to redeploy, and the same string would end up copied into the
 * client, the CSP and the tests — three places to drift.
 * `config/minivic-origin.json` is the one place it is written down; this script
 * turns it into a typed module, `NEXT_PUBLIC_MINIVIC_ORIGIN` overrides it for a
 * build pointed at another deployment, and tests/minivic_chat_route.test.mjs
 * (MV-ROUTE-08) fails the moment config, module and firebase.json's connect-src
 * stop agreeing.
 *
 * The value is public — it is the URL the function is served on, reachable by
 * anyone. Nothing secret passes through here; provider keys stay in Secret
 * Manager, on the far side of that URL.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

import { isUsableChatOrigin } from '../../lib/miniVicRoute.mjs';

const ROOT = resolve(import.meta.dirname, '..', '..');
const CONFIG = resolve(ROOT, 'config/minivic-origin.json');
const OUT = resolve(ROOT, 'app/data/generated/minivic-origin.ts');

const configured = JSON.parse(readFileSync(CONFIG, 'utf8')).originUrl ?? '';
const override = process.env.NEXT_PUBLIC_MINIVIC_ORIGIN;
const candidate = String(
  typeof override === 'string' && override.trim() ? override : configured,
).trim();

// An unusable value is not a build failure: the Hosting rewrite answers every
// send on its own, a little slower. A build that died over it would be worse
// than the latency it protects.
const origin = isUsableChatOrigin(candidate) ? new URL(candidate).origin : '';
if (candidate && !origin) {
  console.warn(
    `[minivic-origin] ${JSON.stringify(candidate)} is not a usable https origin — ` +
      'the direct route is off and every send will take the Hosting rewrite.',
  );
}

const body = `/**
 * GENERATED by scripts/build/minivic_origin.mjs — do not edit.
 *
 * Source of truth: config/minivic-origin.json (overridable at build time with
 * NEXT_PUBLIC_MINIVIC_ORIGIN). An empty string means "no direct route": every
 * send goes through the same-origin /api/chat rewrite, which always works.
 *
 * This URL is public — it is where the chat function is served. No credential is
 * carried here or reachable through it.
 */
export const MINIVIC_CHAT_ORIGIN = ${JSON.stringify(origin)} as const;
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(`[minivic-origin] ${origin || '(none — Hosting rewrite only)'}`);
