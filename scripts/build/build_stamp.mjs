#!/usr/bin/env node
/**
 * Writes `app/data/generated/build-stamp.ts` — the commit these bytes were built
 * from, and whether the tree was clean when they were built.
 *
 * WHY THIS IS A BUILD SCRIPT AND NOT A CALL INSIDE THE COMPONENT
 * -------------------------------------------------------------
 * The first version read git from module scope inside `Footer.tsx`, on the
 * theory that a static export evaluates that once at build time. It does — but
 * not reliably, and not in a context this repository controls: the component
 * sits inside a client boundary, so its module is evaluated by a Next build
 * worker whose working directory and environment are Next's to decide. The
 * symptom was a stamp that rendered from one checkout and silently vanished from
 * another, with git returning the correct commit to every process that asked it
 * directly.
 *
 * `cv_fingerprint.mjs` and `feedback_log.mjs` already establish the pattern for
 * this: run the measurement in a script that owns its own process, write a typed
 * module, and let the component import a value. A number that has to be right
 * belongs where it can be inspected before the build, not inside a bundler's
 * worker.
 *
 * WHAT "CLEAN" MEANS HERE
 * -----------------------
 * Two paths are excluded because the build writes them itself, before this runs:
 * `app/data/generated/` (this file, the CV fingerprint and the corrections
 * ledger, all derived from the commit) and `reports/` (the static audit's own
 * output). Every other tracked difference means hand-edited source that no
 * commit contains — and INCIDENT-01 is what happens when that ships unannounced.
 */

import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..', '..');
const OUT = resolve(ROOT, 'app/data/generated/build-stamp.ts');

const git = (...args) =>
  execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();

const BUILD_WRITES = /^app\/data\/generated\/|^reports\//;

let stamp = { sha: null, authored: null, clean: false };
try {
  const dirty = git('diff', '--name-only', 'HEAD')
    .split('\n')
    .map((p) => p.trim())
    .filter((p) => p && !BUILD_WRITES.test(p));

  stamp = {
    sha: git('rev-parse', '--short=8', 'HEAD'),
    authored: git('log', '-1', '--format=%cI'),
    clean: dirty.length === 0,
  };
  if (!stamp.clean) {
    console.warn(
      `[build-stamp] ${dirty.length} tracked file(s) differ from HEAD — the page will carry no ` +
        `commit stamp, because it was not built from one:\n  ${dirty.join('\n  ')}`,
    );
  }
} catch (error) {
  // A build outside a checkout is legitimate. An invented commit is not.
  console.warn(`[build-stamp] git unavailable (${error.message.split('\n')[0]}); stamp omitted.`);
}

const body = `/**
 * GENERATED by scripts/build/build_stamp.mjs — do not edit.
 *
 * \`sha\` and \`authored\` are null unless the working tree matched HEAD exactly at
 * build time, so the footer can never name a commit these bytes did not come
 * from. Absence is the honest signal; see INCIDENT-01.
 */
export interface BuildStamp {
  /** Short SHA of the commit that produced this build, or null if it was not one. */
  readonly sha: string | null;
  /** ISO 8601 author date of that commit, or null. */
  readonly authored: string | null;
  /** Whether every tracked file matched HEAD when this was written. */
  readonly clean: boolean;
}

export const buildStamp: BuildStamp = ${JSON.stringify(
  stamp.clean ? stamp : { sha: null, authored: null, clean: false },
  null,
  2,
)} as const;
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(
  stamp.clean
    ? `[build-stamp] ${stamp.sha} (${stamp.authored})`
    : '[build-stamp] tree was not clean — no commit stamp will render',
);
