#!/usr/bin/env node
/**
 * feedback_log.mjs — the corrections ledger, harvested from this repository.
 *
 * The closing section claims that feedback is wanted and acted on. Every
 * portfolio claims that. The difference is that this one can produce the
 * receipts, because the site is built from a repository whose history is a
 * list of the times a review found something wrong with it and it was fixed.
 *
 * This reads that history at build time and writes it as data. Nothing here is
 * written by hand, and nothing is selected by sentiment: a commit qualifies
 * only if it is a correction — a `fix` type, or a subject that names a review,
 * an audit or a finding. A commit that adds a feature does not qualify, no
 * matter how nicely its message reads.
 *
 * Run from `npm run build:static`, before `next build`.
 *
 * The output is committed rather than ignored, so a fresh clone typechecks and
 * builds without having to run the harvest first. One consequence is
 * unavoidable and worth stating: writing this file is itself a commit, so the
 * committed copy trails HEAD by exactly one. The page never claims otherwise —
 * it prints how many of the total it is showing, and the date it was
 * harvested.
 */

import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const ROOT = process.cwd();
const OUT = join(ROOT, 'app', 'data', 'generated', 'feedback-log.ts');
const SHOWN = 8;

/** A correction, not a feature. */
const CORRECTION = /^(fix|perf|refactor)\(/i;
const REVIEW_WORDS = /\b(review|reviewer|audit|finding|findings|adversarial|regression|defect|caught|wrong|fabrication)\b/i;

function git(...args) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trimEnd();
}

let raw = '';
try {
  // %x1f between fields, %x1e between records: the only bytes a commit message
  // is guaranteed not to contain.
  raw = git('log', '--no-merges', '-400', '--date=short', '--pretty=format:%h%x1f%ad%x1f%s%x1e');
} catch {
  // No repository (a tarball build, a shallow CI checkout). The section falls
  // back to its own copy rather than failing the build.
  raw = '';
}

const entries = raw
  .split('\x1e')
  .map((record) => record.trim())
  .filter(Boolean)
  .map((record) => {
    const [hash, date, subject] = record.split('\x1f');
    return { hash, date, subject };
  })
  .filter(({ subject }) => subject && (CORRECTION.test(subject) || REVIEW_WORDS.test(subject)))
  .map(({ hash, date, subject }) => {
    // Drop the conventional-commit prefix: the scope is for the log, and the
    // sentence after it is the part a reader of the page needs.
    const said = subject.replace(/^[a-z]+(\([^)]*\))?:\s*/i, '');
    return { hash, date, said: said.charAt(0).toUpperCase() + said.slice(1) };
  });

const shown = entries.slice(0, SHOWN);

const file = `/**
 * GENERATED by scripts/build/feedback_log.mjs — do not edit.
 *
 * The corrections this page has had made to it, read out of the repository's
 * own history at build time. See the script for what qualifies as one.
 */

export interface Correction {
  /** The commit, so a reader can go and read the diff. */
  hash: string;
  /** ISO date, as the commit records it. */
  date: string;
  /** What was wrong, in the words of the commit that fixed it. */
  said: string;
}

export const feedbackLog = {
  /** Every correction in the history, not just the ones printed. */
  total: ${entries.length},
  /** The most recent, newest first. */
  corrections: ${JSON.stringify(shown, null, 2)} as Correction[],
  /** When this was harvested. */
  harvested: '${new Date().toISOString().slice(0, 10)}',
} as const;
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, file);
console.log(
  `[feedback-log] ${entries.length} correction(s) in history; ${shown.length} written to ${OUT.replace(ROOT + '/', '')}`,
);
